DO $do$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ordem_servico_app') THEN
    CREATE ROLE ordem_servico_app NOLOGIN NOSUPERUSER INHERIT NOCREATEDB NOCREATEROLE NOREPLICATION;
  END IF;
END
$do$;

REVOKE CONNECT ON DATABASE ordem_servico FROM PUBLIC;
GRANT CONNECT ON DATABASE ordem_servico TO ordem_servico_app;

REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;

GRANT USAGE, CREATE ON SCHEMA public TO ordem_servico_app;
GRANT ALL ON ALL TABLES IN SCHEMA public TO ordem_servico_app;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO ordem_servico_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO ordem_servico_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO ordem_servico_app;
